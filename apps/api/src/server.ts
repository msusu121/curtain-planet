import 'dotenv/config';
import { PrismaClient } from '@prisma/client';
import { PrismaPg } from '@prisma/adapter-pg';
import { createClient } from 'redis';
import { Client } from 'minio';
import { z } from 'zod';
import { createApp } from './app.js';
import { createAuthService } from './auth/service.ts';
import { createPrismaAuthStore } from './auth/prisma-store.ts';
import { Pool } from 'pg';
import { PostgresBusinessStore } from './business/store.ts';
const env = z.object({DATABASE_URL: z.string().min(1), REDIS_URL: z.string().min(1), MINIO_ENDPOINT: z.string().min(1), MINIO_PORT: z.coerce.number().default(9000), MINIO_ACCESS_KEY: z.string().min(1), MINIO_SECRET_KEY: z.string().min(8), MINIO_BUCKET: z.string().default('curatin-media'), PORT: z.coerce.number().default(4000)}).parse(process.env);
const db = new PrismaClient({adapter: new PrismaPg({connectionString: env.DATABASE_URL, connectionTimeoutMillis: 3000})});
const businessPool = new Pool({connectionString: env.DATABASE_URL, connectionTimeoutMillis: 3000, max: 10});
const redis = createClient({url: env.REDIS_URL, socket: {connectTimeout: 3000, reconnectStrategy: false}});
redis.on('error', () => console.error('Redis connection unavailable'));
const media = new Client({endPoint: env.MINIO_ENDPOINT, port: env.MINIO_PORT, useSSL: process.env.MINIO_USE_SSL === 'true', accessKey: env.MINIO_ACCESS_KEY, secretKey: env.MINIO_SECRET_KEY});
media.setRequestOptions({timeout: 3000});
await redis.connect();
const app = createApp({postgres: () => db.$queryRaw`SELECT 1`, redis: () => redis.ping(), minio: async () => {if (!await media.bucketExists(env.MINIO_BUCKET)) throw new Error('Media bucket unavailable');}}, createAuthService(createPrismaAuthStore(db)), {store: new PostgresBusinessStore(businessPool), pool: businessPool, media, bucket: env.MINIO_BUCKET});
const server = app.listen(env.PORT, '0.0.0.0', () => console.log(`API listening on ${env.PORT}`));
for (const signal of ['SIGINT', 'SIGTERM'] as const) process.on(signal, () => {server.close(() => {void Promise.allSettled([db.$disconnect(), redis.quit(), businessPool.end()]).then(() => process.exit(0));}); setTimeout(() => process.exit(1), 10000).unref();});
